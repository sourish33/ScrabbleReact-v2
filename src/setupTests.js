// jsdom does not implement window.matchMedia; sweetalert2 calls it when
// rendering the success/error icon, so tests that trigger Swal.fire need this stub.
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})
